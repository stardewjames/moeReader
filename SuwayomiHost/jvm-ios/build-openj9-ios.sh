#!/usr/bin/env bash
# Cross-builds Eclipse OpenJ9 (+ OMR) and the OpenJDK 21 class library for iOS arm64 (device or
# simulator), interpreter only. package.sh then prelinks the VM and the JDK's native libraries into
# a static archive for the app (prelink-openj9-ios.py).
#   ./build-openj9-ios.sh iphoneos|iphonesimulator [make targets...]
# Output: work/openj9-jdk21/build/<conf>/ (VM in vm/, classes in jdk/modules, static JDK libs in
#         support/native/*/*/static) and work/openj9-ios/<platform>/ (compiler wrappers).
# Prereq: ./fetch-openj9.sh (Semeru 21 is the boot JDK and the build JDK: it is the
#         exact same JDK version, 21.0.12.1+1, and the same OpenJ9 release).
#
# How the cross build works:
# - OpenJDK's configure sees a cross build to aarch64-apple-darwin (OPENJDK_TARGET_OS=macosx) with
#   the iOS SDK as sysroot. CC/CXX are wrappers (work/openj9-ios/<platform>/bin) that pin
#   `-target arm64-apple-ios<min>[-simulator]` and the iOS SDK and drop macOS-only flags
#   (-mmacosx-version-min, a macOS -isysroot), so every object is an iOS object.
# - OpenJ9's CMake build runs its own tools (hookgen, tracegen, constgen) through OMR_EXE_LAUNCHER =
#   tools/run-ios-tool, which runs a macOS-retagged copy (same CPU and ABI).
# - No JIT (OMR_COMPILER=OFF, codert/jit_vm off), no DDR, non-compressed references (arm64 Mach-O
#   executables reserve the low 4 GB as __PAGEZERO).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
W="$HERE/work"
SRC="$W/openj9-jdk21"
PLATFORM="${1:-iphonesimulator}"; shift || true
IOS_MIN="${IOS_MIN:-26.0}"
JOBS="${JOBS:-12}"
MAKE="$W/tools/bin/make"
SEMERU="$W/semeru21/Contents/Home"
BOOT_JDK="${BOOT_JDK:-$SEMERU}"
BUILD_JDK="${BUILD_JDK:-$SEMERU}"
CUPS_VER=2.4.11
case "$PLATFORM" in
  iphoneos)        CONF=ios-aarch64-openj9-release;    TRIPLE="arm64-apple-ios${IOS_MIN}" ;;
  iphonesimulator) CONF=iossim-aarch64-openj9-release; TRIPLE="arm64-apple-ios${IOS_MIN}-simulator" ;;
  *) echo "usage: build-openj9-ios.sh iphoneos|iphonesimulator [targets]"; exit 1 ;;
esac
# The modules whose native libraries the host needs (linked statically; see prelink-openj9-ios.py,
# run by package.sh).
STATIC_LIB_MODULES="java.base java.prefs java.management jdk.management jdk.net"
TARGETS=("$@")
if [ ${#TARGETS[@]} -eq 0 ]; then
  # OpenJ9 (j9vm-build) is built by the copy targets; "java.base-copy" alone rebuilds just the VM.
  TARGETS=(hotspot java gendata copy)
  for m in $STATIC_LIB_MODULES; do TARGETS+=("$m-static-libs"); done
fi
SDK="$(xcrun --sdk "$PLATFORM" --show-sdk-path)"

# --- compiler wrappers ------------------------------------------------------------------------------
T="$W/openj9-ios/$PLATFORM/bin"
mkdir -p "$T"
for tool in cc c++; do
  real="$(xcrun --sdk "$PLATFORM" -f "$([ $tool = cc ] && echo clang || echo clang++)")"
  cat > "$T/$tool" <<EOF
#!/usr/bin/env bash
# Generated by build-openj9-ios.sh: $tool for $TRIPLE whatever macOS flags the build passes.
args=()
skip=0
for a in "\$@"; do
  if [ \$skip = 1 ]; then skip=0; continue; fi
  case "\$a" in
    -mmacosx-version-min=*|-mmacos-version-min=*|--sysroot=*|--target=*) continue ;;
    -isysroot|-target|-arch) skip=1; continue ;;
    -isysroot*) continue ;;
    -Wl,-macosx_version_min,*|-Wl,-platform_version,*) continue ;;
  esac
  args+=("\$a")
done
exec "$real" -target $TRIPLE -isysroot "$SDK" "\${args[@]}"
EOF
  chmod +x "$T/$tool"
done

"$HERE/apply-openj9-patches.sh"

# --- configure --------------------------------------------------------------------------------------
cd "$SRC"
if [ ! -f "build/$CONF/spec.gmk" ]; then
  # OpenJDK's configure runs its compiler checks in the source root: one configure at a time
  # (the builds themselves may run in parallel).
  mkdir -p build
  until mkdir build/.configure.lock 2>/dev/null; do sleep 2; done
  trap 'rmdir build/.configure.lock 2>/dev/null || true' EXIT
  bash configure \
    --with-conf-name="$CONF" \
    --openjdk-target=aarch64-apple-darwin \
    --with-sysroot="$SDK" \
    --with-boot-jdk="$BOOT_JDK" \
    --with-build-jdk="$BUILD_JDK" \
    --with-debug-level=release \
    --with-native-debug-symbols=none \
    --disable-ddr \
    --disable-jfr \
    --with-noncompressedrefs \
    --with-cups-include="$W/src/cups-${CUPS_VER}" \
    --disable-warnings-as-errors \
    --disable-warnings-as-errors-omr \
    --disable-warnings-as-errors-openj9 \
    --with-vendor-name=MoeReader \
    --without-version-pre --without-version-opt --with-version-build=1 --with-build-user=moereader \
    CC="$T/cc" CXX="$T/c++" \
    BUILD_CC="$(xcrun --sdk macosx -f clang)" BUILD_CXX="$(xcrun --sdk macosx -f clang++)" \
    MAKE="$MAKE"
  rmdir build/.configure.lock
  trap - EXIT
fi

# OpenJ9's CMake options for iOS, read from the environment by closed/OpenJ9.gmk.
export EXTRA_CMAKE_ARGS="\
 -DOMR_EXE_LAUNCHER=$HERE/tools/run-ios-tool\
 -DOMR_COMPILER=OFF -DOMR_JIT=OFF -DJ9VM_MODULE_CODERT_VM=OFF -DJ9VM_MODULE_J9JIT_VM=OFF\
 -DJ9VM_MODULE_J9VMTEST=OFF -DJ9VM_MODULE_JVMTITST=OFF -DJ9VM_MODULE_JNIARGTESTS=OFF\
 -DJ9VM_MODULE_LIFECYCLE_TESTS=OFF -DJ9VM_MODULE_PORTTEST=OFF -DJ9VM_MODULE_ALGORITHM_TEST=OFF\
 -DJ9VM_MODULE_GPTEST=OFF -DJ9VM_MODULE_JNITEST=OFF -DJ9VM_MODULE_SHARED_TEST=OFF\
 -DOMR_FVTEST=OFF"
"$MAKE" CONF="$CONF" JOBS="$JOBS" "${TARGETS[@]}"
