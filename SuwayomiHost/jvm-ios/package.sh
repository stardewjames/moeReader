#!/usr/bin/env bash
# Packages the Suwayomi runtime the app bundles, into $OUT (default
# SuwayomiHost/build/runtime/ios):
#   SuwayomiRuntime/jre/                     jlinked java.home (same classes for device and simulator)
#   SuwayomiRuntime/jvm.options              OpenJ9's option list (SuwayomiJVM.jvmOptions reads it)
#   SuwayomiRuntime/host/suwayomi-host.jar   the host (SuwayomiHost/host)
#   lib/<sdk>/libopenj9.a                    the VM and the JDK's native libraries, prelinked
#   jvm.xcconfig                             per-SDK link flags, included by MoeReader/SuwayomiCompat/Suwayomi.xcconfig
#   licenses/<component>/                    licence and notice files of what is linked in
#
# Prereqs (once, on a Mac with Xcode; see README.md):
#   ./fetch-openj9.sh && ./build-openj9-macos.sh && ./build-openj9-ios.sh iphoneos (and/or iphonesimulator)
# Adapted from the Oneechan runtime's jvm-ios/package.sh (MPL-2.0).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
W="$HERE/work"
OUT="${OUT:-$ROOT/build/runtime/ios}"
RUNTIME="$OUT/SuwayomiRuntime"
# The jlinked modules: what the host jar references (jdeps), minus jdk.javadoc
# (only ICU's doc tools use it), plus extended charsets and CLDR locale data
# (pages in legacy encodings, localized dates) and zipfs (the jar converter).
MODULES="${MODULES:-java.base,java.desktop,java.logging,java.management,java.naming,java.net.http,java.scripting,java.sql,java.xml,jdk.charsets,jdk.localedata,jdk.unsupported,jdk.zipfs}"

SRC="$W/openj9-jdk21"
conf_of() { case "$1" in iphoneos) echo ios-aarch64-openj9-release ;; iphonesimulator) echo iossim-aarch64-openj9-release ;; esac; }
build_of() { echo "$SRC/build/$(conf_of "$1")"; }
mkdir -p "$RUNTIME/host" "$W/trash"

# 1. The host jar, built with a desktop JDK 21.
(cd "$ROOT" && ./gradlew --console=plain -q :host:shadowJar)
cp "$ROOT/host/build/libs/suwayomi-host.jar" "$RUNTIME/host/suwayomi-host.jar"
cp "$HERE/../jvm-options/openj9.options" "$RUNTIME/jvm.options"
# HOST_ONLY=1 refreshes the jar and options in an existing package (CI restores
# the VM part from its cache; the VM is rebuilt only when jvm-ios/ changes).
if [ "${HOST_ONLY:-0}" = 1 ]; then
  for file in "$OUT/jvm.xcconfig" "$RUNTIME/jre/lib/modules"; do
    [ -s "$file" ] || { echo "HOST_ONLY=1 needs an existing package in $OUT (missing $file)" >&2; exit 1; }
  done
  [ -d "$RUNTIME/licenses" ] || { echo "HOST_ONLY=1 needs bundled licenses in $OUT" >&2; exit 1; }
  found_archive=0
  for p in iphoneos iphonesimulator; do
    archive="$OUT/lib/$p/libopenj9.a"
    [ -s "$archive" ] || continue
    found_archive=1
  done
  [ "$found_archive" = 1 ] || { echo "HOST_ONLY=1 needs a packaged OpenJ9 archive in $OUT" >&2; exit 1; }
  du -sh "$RUNTIME/host/suwayomi-host.jar"
  exit 0
fi

# 2. java.home (rebuilt when the module set or the class library changes).
platform=""
for p in iphoneos iphonesimulator; do [ -d "$(build_of $p)/jdk/modules/java.base" ] && { platform=$p; break; }; done
[ -n "$platform" ] || { echo "No iOS OpenJ9 build: run build-openj9-ios.sh first" >&2; exit 1; }
if [ ! -f "$RUNTIME/jre/lib/modules" ] || [ "$(cat "$OUT/jre.modules" 2>/dev/null)" != "openj9:$MODULES" ] \
   || [ -n "$(find "$(build_of "$platform")/jdk/modules" -newer "$RUNTIME/jre/lib/modules" -print -quit)" ] \
   || [ "$HERE/jlink-ios.sh" -nt "$RUNTIME/jre/lib/modules" ]; then
  [ ! -e "$RUNTIME/jre" ] || mv "$RUNTIME/jre" "$W/trash/jre.$$.$RANDOM"
  "$HERE/jlink-ios.sh" "$platform" "$RUNTIME/jre" "$MODULES"
  echo "openj9:$MODULES" > "$OUT/jre.modules"
fi
# jlink links duplicate legal notices to java.base's; the app bundle gets plain files instead.
find "$RUNTIME/jre" -type l | while read -r link; do cp -L "$link" "$link.tmp" && mv -f "$link.tmp" "$link"; done

# 3. The static VM per SDK, and the link flags that pull it in.
{
  echo "// Generated by SuwayomiHost/jvm-ios/package.sh: links the static OpenJ9 JVM into the app."
  echo "// The shim finds JNI_CreateJavaVM in the executable, so nothing may be dead-stripped."
  echo "// SDKs without a packaged VM keep the app's default dead stripping."
  for p in iphoneos iphonesimulator; do
    B="$(build_of "$p")"
    [ -f "$B/vm/runtime/libj9vm29.dylib" ] || continue
    P="$W/openj9-ios/$p/prelinked"
    python3 -I "$HERE/prelink-openj9-ios.py" "$p" "$B" "$P" >&2
    mkdir -p "$OUT/lib/$p"
    cp "$P/libopenj9.a" "$OUT/lib/$p/libopenj9.a"
    flags="$(cat "$P/link-flags.txt")"
    archive="$P/libopenj9.a"
    flags="${flags//"$archive"/\"\$(PROJECT_DIR)/SuwayomiHost/build/runtime/ios/lib/$p/libopenj9.a\"}"
    echo "SUWAYOMI_JVM_LDFLAGS[sdk=$p*] = $flags"
    echo "SUWAYOMI_JVM_DEAD_CODE_STRIPPING[sdk=$p*] = NO"
  done
} > "$OUT/jvm.xcconfig"

# 4. Licence and notice files of the linked-in components (bundled with the app).
L="$OUT/licenses"
[ ! -e "$L" ] || mv "$L" "$W/trash/licenses.$$.$RANDOM"
mkdir -p "$L/openj9" "$L/omr" "$L/openjdk" "$L/libffi" "$L/zlib"
cp "$SRC/openj9/LICENSE" "$SRC/openj9/NOTICES.md" "$SRC/openj9/epl-2.0.html" "$L/openj9/"
cp "$SRC/omr/LICENSE" "$SRC/omr/NOTICE.md" "$L/omr/"
cp "$SRC/LICENSE" "$SRC/ASSEMBLY_EXCEPTION" "$SRC/ADDITIONAL_LICENSE_INFO" "$SRC/openj9-openjdk-notices" "$L/openjdk/"
cp "$SRC/openj9/runtime/libffi/LICENSE" "$L/libffi/LICENSE"
sed -n '/^  Copyright (C)/,/^  Jean-loup Gailly/p' "$SRC/openj9/runtime/include/zlib.h" | sed 's/^  //' > "$L/zlib/LICENSE"
[ ! -e "$RUNTIME/licenses" ] || mv "$RUNTIME/licenses" "$W/trash/runtime-licenses.$$.$RANDOM"
cp -R "$L" "$RUNTIME/licenses"

sed 's/ -force_load / … /g' "$OUT/jvm.xcconfig" | cut -c1-160
du -sh "$RUNTIME/jre" "$RUNTIME/host/suwayomi-host.jar" "$OUT/lib"/* 2>/dev/null || true
